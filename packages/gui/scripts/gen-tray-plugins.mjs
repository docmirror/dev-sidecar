/**
 * 打包/启动前扫描一次插件 config，生成托盘静态插件表。
 * 输出：src/generated/tray-plugins.js
 *
 * 【临时方案】当前尚未实现运行时动态插件，插件清单在打包后固定。
 * 本脚本只是在打包期扫一次 config 元数据，避免手写表；
 * 将来若支持动态插件，应改为启动时从插件注册表读取，并废弃该生成物。
 *
 * 新增插件只要在 config.js 里写 name / statusOff / needUnlock / restartServer，
 * 重新执行本脚本（或 build / electron）即可，无需手改托盘代码。
 *
 * 用源码解析而非 require：free-eye 的 config 是 ESM，其余是 CJS。
 *
 * 输出两类：
 *   TRAY_PLUGINS — checkbox 开关（statusOff=false）
 *   TRAY_ACTIONS — 一键动作菜单（statusOff=true 但可运行，如网络检测）
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const pluginRootCandidates = [
  path.resolve(__dirname, '../../../packages/core/src/modules/plugin'),
]

const pluginRoot = pluginRootCandidates.find(p => fs.existsSync(p))
if (!pluginRoot) {
  console.error(`[gen-tray-plugins] 找不到插件目录，已尝试:\n  ${pluginRootCandidates.join('\n  ')}`)
  process.exit(1)
}

/** 从源码文本取顶层字面量字段（避免嵌套 name / 行注释干扰） */
function pickTopField (src, field) {
  // 去掉行注释，避免 `true, // xxx` 被当成值
  const line = src
    .split('\n')
    .map(l => l.replace(/\/\/.*$/, ''))
    .join('\n')
  // 仅匹配缩进较浅的 `field: value`（export/module.exports 对象第一层）
  const re = new RegExp(`^\\s{0,4}${field}:\\s*(.+?)\\s*,?\\s*$`, 'm')
  const m = line.match(re)
  if (!m) {
    return undefined
  }
  const raw = m[1].trim().replace(/,.*$/, '').trim()
  if (raw === 'true') {
    return true
  }
  if (raw === 'false') {
    return false
  }
  const str = raw.match(/^['"]([^'"]*)['"]$/)
  if (str) {
    return str[1]
  }
  return raw
}

/** 运行时 key：优先 index.js 导出块里的 key: 'xxx' */
function parseKey (indexSrc, dirName) {
  const block = indexSrc.match(/(?:module\.exports|export\s+default)\s*=\s*\{([\s\S]*?)\n\}/)
  const src = block ? block[1] : indexSrc
  const m = src.match(/^\s*key:\s*['"]([\w-]+)['"]/m)
  if (m) {
    return m[1]
  }
  // free-eye 目录 → free_eye
  return dirName.replace(/-/g, '_')
}

/** 该插件是否有可调用的 run/start 动作 */
function hasRunAction (indexSrc) {
  return /\brun\s*[:(]|async\s+run\s*\(/.test(indexSrc)
}

const all = []
const switches = []
const actions = []

for (const name of fs.readdirSync(pluginRoot)) {
  const dir = path.join(pluginRoot, name)
  if (!fs.statSync(dir).isDirectory()) {
    continue
  }
  const configPath = path.join(dir, 'config.js')
  if (!fs.existsSync(configPath)) {
    continue
  }
  const configSrc = fs.readFileSync(configPath, 'utf-8')
  const indexPath = path.join(dir, 'index.js')
  const indexSrc = fs.existsSync(indexPath) ? fs.readFileSync(indexPath, 'utf-8') : ''
  const key = parseKey(indexSrc, name)
  const confName = pickTopField(configSrc, 'name') || key
  const statusOff = pickTopField(configSrc, 'statusOff') === true
  const needUnlock = pickTopField(configSrc, 'needUnlock') === true
  const restartServer = pickTopField(configSrc, 'restartServer') === true
  const hasRun = hasRunAction(indexSrc)

  const rec = { key, name: confName, statusOff, needUnlock, restartServer, hasRun }
  all.push(rec)

  // statusOff 且有 run() → 一键动作菜单（如网络检测）
  // statusOff 且无 run() → 不上托盘（如 pip）
  // 非 statusOff → checkbox 开关
  if (!statusOff) {
    switches.push({ key, name: confName, needUnlock, restartServer })
  } else if (hasRun) {
    actions.push({ key, name: confName })
  }
}

// 稳定顺序：先常驻，后需解锁；同组按 key
switches.sort((a, b) => {
  if (a.needUnlock !== b.needUnlock) {
    return a.needUnlock ? 1 : -1
  }
  return a.key.localeCompare(b.key)
})
actions.sort((a, b) => a.key.localeCompare(b.key))

const outDir = path.resolve(__dirname, '../src/generated')
fs.mkdirSync(outDir, { recursive: true })
const outFile = path.join(outDir, 'tray-plugins.js')

const body = `// AUTO-GENERATED by scripts/gen-tray-plugins.mjs — DO NOT EDIT
// 扫描来源: ${path.relative(path.resolve(__dirname, '..'), pluginRoot).replace(/\\/g, '/')}
// 生成时间: ${new Date().toISOString()}
//
// 【临时方案】当前尚未实现运行时动态插件，本表在打包期固定。
// 动态插件落地后应改为启动时读插件注册表，并废弃本文件。
//
// 扫描插件 ${all.length} 个：开关 ${switches.length} 个、一键动作 ${actions.length} 个、其余不上托盘。

/** checkbox 开关（statusOff=false） */
export const TRAY_PLUGINS = ${JSON.stringify(switches, null, 2)}

/** 一键动作菜单（statusOff=true 但有 run()，如网络检测） */
export const TRAY_ACTIONS = ${JSON.stringify(actions, null, 2)}
`

fs.writeFileSync(outFile, body, 'utf-8')

// 清晰的扫描报告
console.log(`[gen-tray-plugins] 扫描插件 ${all.length} 个 → ${path.relative(process.cwd(), outFile)}`)
console.log('')
for (const r of all) {
  const flags = []
  if (r.statusOff) flags.push('statusOff')
  if (r.needUnlock) flags.push('needUnlock')
  if (r.restartServer) flags.push('restartServer')
  if (r.hasRun) flags.push('hasRun')
  let dest
  if (!r.statusOff) {
    dest = '托盘开关'
  } else if (r.hasRun) {
    dest = '托盘一键动作'
  } else {
    dest = '不上托盘'
  }
  console.log(`  - ${r.key.padEnd(12)} ${String(r.name).padEnd(12)} → ${dest}${flags.length ? ` [${flags.join(', ')}]` : ''}`)
}
console.log('')
console.log(`  合计: 开关 ${switches.length} | 一键动作 ${actions.length} | 不上托盘 ${all.length - switches.length - actions.length}`)
